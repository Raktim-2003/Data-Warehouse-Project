DROP TABLE IF EXISTS silver_cust_info;
DROP TABLE IF EXISTS silver_prd_info;
DROP TABLE IF EXISTS silver_sales_details;


-- 1st table create 

CREATE TABLE silver_cust_info (
    cst_id INT,
    cst_key VARCHAR(50),
    cst_firstname VARCHAR(50),
    cst_lastname VARCHAR(50),
    cst_marital_status VARCHAR(50),
    cst_gndr VARCHAR(50),
    cst_create_date DATE,
    dwh_created_date DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 2st table create 

CREATE TABLE silver_prd_info (
    prd_id INT,
    cat_id VARCHAR(50),
    prd_key VARCHAR(50),
    prd_nm VARCHAR(50),
    prd_cost INT,
    prd_line VARCHAR(50),
    prd_start_dt DATE,
    prd_end_dt DATE,
    dwh_created_date DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 3st table create 

CREATE TABLE silver_sales_details (
    sls_ord_num VARCHAR(50),
    sls_prd_key VARCHAR(50),
    sls_cust_id INT,
    sls_order_dt DATE,
    sls_ship_dt DATE,
    sls_due_dt DATE,
    sls_sales INT,
    sls_quantity INT,
    sls_price INT,
    dwh_created_date DATETIME DEFAULT CURRENT_TIMESTAMP
);
